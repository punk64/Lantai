alter table LIBRARY
    add column TYPE varchar NOT NULL DEFAULT 'LOCAL';

CREATE TABLE ONLINE_MANGA
(
    ID                 varchar  NOT NULL PRIMARY KEY,
    CREATED_DATE       datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
    LAST_MODIFIED_DATE datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
    SERIES_ID          varchar  NOT NULL,
    SOURCE_KIND        varchar  NOT NULL DEFAULT 'plugin',
    REMOTE_MANGA_ID    varchar  NOT NULL,
    TITLE              varchar  NOT NULL,
    COVER_URL          varchar  NULL,
    STATUS             varchar  NULL,
    LAST_SYNC_AT       datetime NULL,
    FOREIGN KEY (SERIES_ID) REFERENCES SERIES (ID)
);

CREATE UNIQUE INDEX IDX__ONLINE_MANGA__REMOTE ON ONLINE_MANGA (SOURCE_KIND, REMOTE_MANGA_ID);

CREATE UNIQUE INDEX IDX__ONLINE_MANGA__SERIES ON ONLINE_MANGA (SERIES_ID);

CREATE TABLE ONLINE_CHAPTER
(
    ID                   varchar  NOT NULL PRIMARY KEY,
    CREATED_DATE         datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
    LAST_MODIFIED_DATE   datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
    MANGA_ID             varchar  NOT NULL,
    BOOK_ID              varchar  NOT NULL,
    IDX                  int      NOT NULL,
    REMOTE_ID            bigint   NOT NULL DEFAULT 0,
    REMOTE_CHAPTER_INDEX int      NOT NULL,
    TITLE                varchar  NOT NULL,
    PAGE_COUNT           int      NOT NULL DEFAULT -1,
    DOWNLOADED           boolean  NOT NULL DEFAULT 0,
    FOREIGN KEY (MANGA_ID) REFERENCES ONLINE_MANGA (ID),
    FOREIGN KEY (BOOK_ID) REFERENCES BOOK (ID)
);

CREATE UNIQUE INDEX IDX__ONLINE_CHAPTER__MANGA_IDX ON ONLINE_CHAPTER (MANGA_ID, IDX);

CREATE UNIQUE INDEX IDX__ONLINE_CHAPTER__BOOK ON ONLINE_CHAPTER (BOOK_ID);
