CREATE TABLE "READING_STATS_DAILY"
(
  "USER_ID"            VARCHAR(32) NOT NULL,
  "DAY"                DATE        NOT NULL,
  "BOOK_ID"            VARCHAR(32) NOT NULL,
  "BOOK_NAME"          VARCHAR(1024) NOT NULL DEFAULT '',
  "SERIES_ID"          VARCHAR(32) NOT NULL DEFAULT '',
  "LIBRARY_ID"         VARCHAR(32) NOT NULL DEFAULT '',
  "DURATION_MS"        BIGINT      NOT NULL DEFAULT 0,
  "PAGES_READ"         INT         NOT NULL DEFAULT 0,
  "SESSION_COUNT"      INT         NOT NULL DEFAULT 0,
  "LAST_READ_AT"       DATETIME    NULL,
  "LAST_MODIFIED_DATE" DATETIME    NOT NULL,
  PRIMARY KEY ("USER_ID", "DAY", "BOOK_ID")
);

CREATE INDEX "idx__reading_stats_daily_user_day" ON "READING_STATS_DAILY" ("USER_ID", "DAY");
