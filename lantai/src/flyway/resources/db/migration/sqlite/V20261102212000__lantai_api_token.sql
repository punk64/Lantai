CREATE TABLE "API_TOKEN"
(
  "ID"                 VARCHAR(32)  NOT NULL,
  "USER_ID"            VARCHAR(32)  NOT NULL,
  "NAME"               VARCHAR(128) NOT NULL,
  "TOKEN_VALUE"        VARCHAR(64)  NOT NULL,
  "SCOPES"             VARCHAR(512) NOT NULL,
  "ENABLED"            BOOLEAN      NOT NULL DEFAULT 1,
  "EXPIRES_DATE"       DATETIME,
  "LAST_USED_DATE"     DATETIME,
  "LAST_USED_IP"       VARCHAR(64),
  "USE_COUNT"          INTEGER      NOT NULL DEFAULT 0,
  "CREATED_DATE"       DATETIME     NOT NULL,
  "LAST_MODIFIED_DATE" DATETIME     NOT NULL,
  PRIMARY KEY ("ID"),
  FOREIGN KEY ("USER_ID") REFERENCES "USER" ("ID") ON DELETE CASCADE
);

CREATE UNIQUE INDEX "idx__api_token_name" ON "API_TOKEN" ("NAME");

CREATE UNIQUE INDEX "idx__api_token_value" ON "API_TOKEN" ("TOKEN_VALUE");

CREATE INDEX "idx__api_token_user_id" ON "API_TOKEN" ("USER_ID");
